use crate::parse::{PluginIr, Registration, RegistrationKind};

/// Write a Rust `register` function for the parsed registrations.
///
/// Callback bodies are empty. Each stub names the original PHP function.
pub fn emit_skeleton(ir: &PluginIr) -> String {
    let mut out = String::new();
    out.push_str("// Generated by oxidepress-rustify.\n");
    if !ir.header.name.is_empty() {
        out.push_str("// Plugin: ");
        out.push_str(&one_line(&ir.header.name));
        out.push('\n');
    }
    out.push_str("// PHP callback bodies are not executed.\n\n");
    out.push_str("pub fn register(\n");
    out.push_str("    hooks: &oxidepress_core::hooks::HookRegistry,\n");
    out.push_str("    shortcodes: &oxidepress_core::shortcode::ShortcodeRegistry,\n");
    out.push_str(") {\n");
    for registration in &ir.registrations {
        out.push_str(&emit_registration(registration));
    }
    out.push_str("}\n");
    out
}

fn emit_registration(registration: &Registration) -> String {
    let tag = rust_string(&registration.tag);
    let comment = format!(
        "// Original PHP function: {}",
        one_line(&registration.callback)
    );
    match registration.kind {
        RegistrationKind::Action => format!(
            "    hooks.add_action(\n        {tag},\n        std::sync::Arc::new(|_args: &serde_json::Value| {{\n            {comment}\n        }}),\n        {},\n    );\n",
            registration.priority
        ),
        RegistrationKind::Filter => format!(
            "    hooks.add_filter(\n        {tag},\n        std::sync::Arc::new(|value: serde_json::Value| {{\n            {comment}\n            value\n        }}),\n        {},\n    );\n",
            registration.priority
        ),
        RegistrationKind::Shortcode => format!(
            "    shortcodes.add_shortcode(\n        {tag},\n        std::sync::Arc::new(|_attrs: &std::collections::BTreeMap<String, String>, _content: &str| {{\n            {comment}\n            String::new()\n        }}),\n    );\n"
        ),
    }
}

fn rust_string(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            _ => out.push(ch),
        }
    }
    out.push('"');
    out
}

fn one_line(value: &str) -> String {
    value.replace(['\n', '\r'], " ")
}
